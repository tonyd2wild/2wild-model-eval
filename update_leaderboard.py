#!/usr/bin/env python3
"""
update_leaderboard.py — rebuild LEADERBOARD.md from every results/*.json file.

Sorted by Deployability (desc). One row per result file.

    python3 update_leaderboard.py
"""

import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(HERE, "results")
LEADERBOARD = os.path.join(HERE, "LEADERBOARD.md")


def load_rows():
    rows = []
    for path in glob.glob(os.path.join(RESULTS_DIR, "*.json")):
        try:
            with open(path) as f:
                data = json.load(f)
        except Exception:
            continue
        meta = data.get("meta", {})
        agg = data.get("aggregate", {})
        if not agg:
            continue
        stars = agg.get("stars", 0)
        rows.append({
            "label": meta.get("label", "?"),
            "model": meta.get("model", "?"),
            "quality": agg.get("quality", 0.0),
            "responsiveness": agg.get("responsiveness", 0.0),
            "deployability": agg.get("deployability", 0.0),
            "token_efficiency": agg.get("token_efficiency", 0.0),
            "passed": agg.get("passed", 0),
            "partial": agg.get("partial", 0),
            "failed": agg.get("failed", 0),
            "scenarios": agg.get("scenarios", 0),
            "stars": stars,
            "star_str": "★" * stars + "☆" * (5 - stars),
            "date": meta.get("utc", "")[:10],
            "file": os.path.basename(path),
        })
    rows.sort(key=lambda r: r["deployability"], reverse=True)
    return rows


def render(rows):
    out = []
    out.append("# 2Wild Model-Eval Leaderboard")
    out.append("")
    out.append("Auto-generated by `update_leaderboard.py` from `results/*.json`. "
               "Sorted by Deployability (0.7·Quality + 0.3·Responsiveness).")
    out.append("")
    if not rows:
        out.append("_No results yet. Run `run_eval.py` to add a row._")
        out.append("")
        return "\n".join(out)
    out.append("| Model | Quality | Resp. | Deploy. | Tok-Eff | ✅/⚠️/❌ | Stars | Date |")
    out.append("|---|---:|---:|---:|---:|:---:|:---:|---|")
    for r in rows:
        pof = f"{r['passed']}/{r['partial']}/{r['failed']}"
        out.append(
            f"| {r['label']} (`{r['model']}`) "
            f"| {r['quality']:.1f} "
            f"| {r['responsiveness']:.1f} "
            f"| {r['deployability']:.1f} "
            f"| {r['token_efficiency']:.3f} "
            f"| {pof} "
            f"| {r['star_str']} "
            f"| {r['date']} |"
        )
    out.append("")
    return "\n".join(out)


def main():
    rows = load_rows()
    with open(LEADERBOARD, "w") as f:
        f.write(render(rows))
    print(f"Wrote {LEADERBOARD} ({len(rows)} row(s)).")


if __name__ == "__main__":
    main()
